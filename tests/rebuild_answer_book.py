def main() -> None:
    data = json.loads(ASSET.read_text(encoding="utf-8"))
    answers = data["answers"]
    assert len(answers) == LITSUM_COUNT + MY_COUNT, (
        f"当前词条 {len(answers)} 条，预期 {LITSUM_COUNT + MY_COUNT} 条（重建前状态）"
    )
    my_entries = answers[LITSUM_COUNT:]
    assert len(my_entries) == MY_COUNT, "自写词条定位失败"
    my_set = set(my_entries)

    pool: list[str] = []
    seen: set[str] = set(my_set)
    skipped: list[str] = []

    for raw in KEEPS + REWRITES + FILLER:
        a = raw.strip()
        if not a or a in seen:
            skipped.append(a)
            continue
        seen.add(a)
        pool.append(a)

    need = TARGET_TOTAL - MY_COUNT
    if len(pool) < need:
        raise SystemExit(f"候选去重后仅 {len(pool)} 条，不足 {need} 条")

    final = my_entries + pool[:need]
    assert len(final) == TARGET_TOTAL and len(set(final)) == TARGET_TOTAL

    random.Random(2026).shuffle(final)

    ASSET.write_text(
        json.dumps({"answers": final}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(
        f"保留自写 {len(my_entries)} 条；"
        f"经典风格候选 {len(KEEPS)} 保留 + {len(REWRITES)} 重写 + {len(FILLER)} 新增，"
        f"去重后可用 {len(pool)} 条（跳过重复 {len(skipped)} 条），取 {need} 条"
    )
    if skipped:
        print(f"跳过: {skipped}")
    print(f"最终 {len(final)} 条，已按固定种子(2026)打乱排序")


if __name__ == "__main__":
    main()
