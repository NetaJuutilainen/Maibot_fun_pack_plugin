def main() -> None:
    data = json.loads(ASSET.read_text(encoding="utf-8"))
    existing = data["answers"]
    seen = {a.strip() for a in existing}

    added: list[str] = []
    skipped_dup: list[str] = []
    for raw in NEW_ANSWERS:
        a = raw.strip()
        if not a:
            continue
        if a in seen:
            skipped_dup.append(a)
            continue
        seen.add(a)
        added.append(a)

    target = 400
    if len(added) < target:
        raise SystemExit(f"候选去重后只有 {len(added)} 条新答案，不足 {target} 条，需要补充候选")

    final = existing + added[:target]
    assert len(final) == len(set(final)), "合并后出现重复词条"
    ASSET.write_text(
        json.dumps({"answers": final}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    print(f"原有 {len(existing)} 条；新增 {min(len(added), target)} 条；共 {len(final)} 条")
    if skipped_dup:
        print(f"跳过与现有重复的候选 {len(skipped_dup)} 条: {skipped_dup}")
    print(f"未用上的候选 {len(added) - target} 条: {added[target:]}")


if __name__ == "__main__":
    main()
